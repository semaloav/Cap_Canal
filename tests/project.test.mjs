import assert from "node:assert/strict";
import {newProject,validateProject,stationList,buildSections,gradeAt,terrainAt,planAt,parseProfile,parseStation,stationLabel} from "../lib/project.mjs";
const old={name:"Legado",project:"",author:"",location:"",section:"rectangular",q:0.25,b:0.5,z:1,n:0.015,s:0.002,height:0.8,freeboard:0.2,vmin:0.3,vmax:3,notes:""};
const migrated=validateProject(old);assert.equal(migrated.grades[0].slope,.002);assert.equal(migrated.profile.length,0);
const d=newProject({...old,start:100,end:195,step:20,startInvert:1000,grades:[{end:150,slope:.01},{end:195,slope:.02}],profile:[{station:100,ground:1001},{station:130,ground:1000.9},{station:195,ground:999.5}]});
assert.deepEqual(stationList(d),[100,120,130,140,150,160,180,195]);
assert.equal(gradeAt(d,150).slope,.02);assert.ok(Math.abs(gradeAt(d,195).invert-998.6)<1e-10);
assert.equal(terrainAt(d.profile,100),1001);assert.equal(terrainAt(d.profile,99),null);assert.ok(Math.abs(terrainAt(d.profile,115)-1000.95)<1e-10);
d.overrides={"150":{b:.9,n:.02}};
let rows=buildSections(d);assert.equal(rows.find(a=>a.station===150).section.b,.9);
assert.equal(rows.find(a=>a.station===140).section.b,.5);assert.equal(rows.find(a=>a.station===150).section.s,.02);
d.b=.7;rows=buildSections(d);assert.equal(rows.find(a=>a.station===150).section.b,.9);assert.equal(rows.find(a=>a.station===140).section.b,.7);
delete d.overrides["150"];assert.equal(buildSections(d).find(a=>a.station===150).section.b,.7);
const curve=newProject({start:0,end:Math.PI*50,step:20,planEnabled:true,easting:1000,northing:2000,azimuth:0,plan:[{end:Math.PI*50,type:"curva",radius:100,turn:"derecha"}],grades:[{end:Math.PI*50,slope:.001}]});
const end=planAt(curve,curve.end);assert.ok(Math.abs(end.easting-1100)<1e-9);assert.ok(Math.abs(end.northing-2100)<1e-9);assert.ok(Math.abs(end.azimuth-90)<1e-9);
const left={...curve,plan:[{...curve.plan[0],turn:"izquierda"}]};assert.ok(Math.abs(planAt(left,left.end).easting-900)<1e-9);
assert.equal(parseStation("1+025.50"),1025.5);assert.equal(parseStation("25,5"),25.5);
assert.deepEqual(parseProfile("0+000\t100,5\n0+050;99.8"),[{station:0,ground:100.5},{station:50,ground:99.8}]);
assert.throws(()=>parseProfile("progresiva cota"));assert.throws(()=>parseStation("0+1000"));
assert.throws(()=>validateProject({...d,grades:[{end:180,slope:.01}]}));
assert.throws(()=>validateProject({...d,profile:[{station:100,ground:1},{station:100,ground:2}]}));
assert.throws(()=>validateProject({...d,overrides:{"150":{b:0}}}));
assert.throws(()=>validateProject({...d,step:.00001}));
assert.throws(()=>validateProject({...d,grades:[{end:195,slope:0}]}));
