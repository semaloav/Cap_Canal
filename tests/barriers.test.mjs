import assert from "node:assert/strict";
import {G} from "../lib/hydraulics.mjs";
import {newProject,validateProject,buildSections} from "../lib/project.mjs";
import {newBarrier,barrierRating} from "../lib/barriers.mjs";
const d=newProject({section:"rectangular",b:1,height:1,freeboard:.1});
const a={...newBarrier(35),crest:.5,analysis:true,upstream:.8,downstream:0,cdWeir:.62};
const r=barrierRating(a,d);assert.ok(Math.abs(r.over-(2/3)*.62*Math.sqrt(2*G)*.3**1.5)<1e-12);assert.equal(r.under,0);
const submerged={...a,mode:"underflow",opening:.15,crest:1,upstream:.9,downstream:.4};
const o=barrierRating(submerged,d);assert.ok(Math.abs(o.under-.61*.15*Math.sqrt(2*G*.5))<1e-12);assert.equal(o.over,0);
const free={...submerged,downstream:0};const rf=barrierRating(free,d);assert.ok(Math.abs(rf.under-.61*(2/3)*Math.sqrt(2*G)*(.9**1.5-.75**1.5))<1e-12);
const mixed=barrierRating({...submerged,crest:.5},d);assert.ok(mixed.over>0&&mixed.under>0);assert.equal(mixed.total,mixed.over+mixed.under);
const drowned=barrierRating({...a,downstream:.6},d);assert.equal(drowned.over,null);assert.equal(drowned.total,null);
assert.equal(barrierRating({...submerged,upstream:.1,downstream:0},d).under,null);
assert.equal(barrierRating({...a,upstream:.2,downstream:.4},d).total,null);
d.barriers=[a];const saved=validateProject(d),rows=buildSections(saved);assert.equal(saved.barriers[0].thickness,.005);assert.equal(rows.find(row=>row.station===35).barriers.length,1);
assert.throws(()=>validateProject({...d,barriers:[{...a,opening:.6}]}));
assert.throws(()=>validateProject({...d,barriers:[{...a,station:100}]}));
assert.throws(()=>validateProject({...d,barriers:[a,{...a,id:crypto.randomUUID()}]}));
assert.throws(()=>validateProject({...d,barriers:[{...a,crest:2}]}));
const trap={...d,section:"trapezoidal",z:1};const t=barrierRating(a,trap);assert.ok(t.over>r.over);assert.ok(t.warnings.length>0);
assert.equal(validateProject({...d,barriers:[]}).barriers.length,0);
console.log("Barrajes: rebose, orificio libre/sumergido, descarga mixta, límites, persistencia y malla: OK.");
