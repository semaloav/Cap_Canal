import assert from "node:assert/strict";
import {renderToStaticMarkup} from "react-dom/server";
import {newProject} from "../lib/project.mjs";
import {newBarrier} from "../lib/barriers.mjs";
import {solveGVF} from "../lib/gvf.mjs";
import GVFView,{GVFTable} from "../app/gvf-view";
import Report from "../app/project-report";
import {buildSections} from "../lib/project.mjs";
import {calculate} from "../lib/hydraulics.mjs";
import type {Project,GVFSolution,SectionRow} from "../app/types";
const d=newProject({name:"Prueba FGV",section:"rectangular",b:1,q:.2,n:.015,height:2,freeboard:.1,s:.001,grades:[{end:100,slope:.001}],gvf:{depth:.7},barriers:[{...newBarrier(50),mode:"underflow",opening:.1,crest:1.5}]}) as Project;
const solution=solveGVF(d) as unknown as GVFSolution;
assert.equal(solution.complete,true);
const html=renderToStaticMarkup(<GVFView d={d} solution={solution} onChange={()=>{}} onCSV={()=>{}}/>);
for(const text of ["Tirante en el contorno","Iteraciones por progresiva","Aguas arriba","Aguas abajo","niveles calculados","Control barraje"])assert.ok(html.includes(text),text);
for(const text of ["Número de secciones base","Iterar FGV cada X metros","Malla de secciones","Origen de sección","S₀ paso (m/m)"])assert.ok(html.includes(text),text);
assert.ok(html.includes('0+050.005000'));assert.ok(html.includes('0+050.000000'));
const report=renderToStaticMarkup(<Report d={d} rows={buildSections(d) as SectionRow[]} gvf={solution} typical={calculate(d)} date="2026-10-18" revision={1} dirty={false}/>);
for(const text of ["Perfil calculado","Error E (m)","Q rebose","Referencia uniforme local"])assert.ok(report.includes(text),text);
assert.ok(report.includes("Malla de secciones"));assert.ok(report.includes("y ensayo"));
assert.ok(!report.includes("Este elemento no modifica automáticamente"));
const failed=solveGVF({...d,gvf:{...d.gvf,depth:.001}}) as unknown as GVFSolution;
const failedHTML=renderToStaticMarkup(<GVFTable solution={failed} print/>);
assert.ok(failedHTML.includes("Sin calcular"));assert.ok(!failedHTML.includes("Converge"));
console.log("FGV interfaz y anexo: contornos, tabla, caras calculadas, controles y resultados incompletos: OK");

